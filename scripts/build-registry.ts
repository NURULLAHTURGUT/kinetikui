/**
 * Builds every published artifact from packages/registry:
 *
 *   public/r/<name>.json          shadcn-compatible registry items (with file contents)
 *   public/r/registry.json        registry index
 *   public/r/src/**               install-layout copies of every file (for GitHub-direct installs)
 *   registry.json                 root index pointing at public/r/src (shadcn GitHub registries)
 *   packages/registry/demos.generated.ts   demo index for the playground and docs
 *
 * Usage: tsx scripts/build-registry.ts [--check]
 *   --check  fail if any output is stale instead of writing it (used in CI)
 */
import fs from 'node:fs';
import path from 'node:path';

import {
  CATEGORIES,
  PUBLIC_DIR,
  REGISTRY_DIR,
  REGISTRY_URL,
  ROOT,
  buildItems,
  installDependencies,
  itemUrl,
  type BuiltItem,
} from './lib/registry';

const check = process.argv.includes('--check');
const outputs = new Map<string, string>();
const emit = (file: string, content: string) => outputs.set(path.join(ROOT, file), content);
const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

const ITEM_SCHEMA = 'https://ui.shadcn.com/schema/registry-item.json';
const REGISTRY_SCHEMA = 'https://ui.shadcn.com/schema/registry.json';

const items = buildItems();

function itemMeta(item: BuiltItem) {
  return {
    version: item.version,
    kind: item.kind,
    platforms: ['ios', 'android', ...(item.meta?.web === 'live' ? ['web'] : [])],
    ...(item.meta
      ? {
          category: item.meta.category,
          web: item.meta.web,
          perf: item.meta.perf,
          a11y: item.meta.a11y,
        }
      : null),
    requires: 'React Native New Architecture (Reanimated 4)',
  };
}

/** The component's docs.mdx, so agents (MCP get_component) can read when to use it. */
function guide(item: BuiltItem) {
  if (!item.dir) return null;
  const file = path.join(item.dir, 'docs.mdx');
  if (!fs.existsSync(file)) return null;
  return { guide: fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') };
}

/** Screens are shadcn blocks; components and shared code are plain items. */
const registryType = (item: BuiltItem) =>
  item.kind === 'template' ? 'registry:block' : 'registry:item';

function toRegistryItem(item: BuiltItem) {
  return {
    $schema: ITEM_SCHEMA,
    name: item.name,
    type: registryType(item),
    title: item.title,
    description: item.description,
    ...(item.meta ? { categories: [item.meta.category] } : null),
    dependencies: installDependencies(item.dependencies),
    registryDependencies: item.registryDependencies.map(itemUrl),
    files: item.builtFiles.map((f) => ({
      path: publicPath(f.target),
      type: 'registry:file',
      target: f.target,
      content: f.content,
    })),
    meta: { ...itemMeta(item), ...guide(item) },
    ...(item.kind !== 'shared'
      ? {
          docs: `Prefer \`npx kinetik-ui add ${item.name}\`: it installs dependencies with expo install, so versions match your Expo SDK.`,
        }
      : null),
  };
}

/** Install-layout copy of a file, relative to public/r (where the item JSON lives). */
const publicPath = (target: string) => `src/${target.replace(/^~\//, '')}`;
const installPath = (target: string) => `public/r/${publicPath(target)}`;

for (const item of items) {
  emit(`public/r/${item.name}.json`, json(toRegistryItem(item)));
  for (const f of item.builtFiles) emit(installPath(f.target), f.content);
}

const index = (filePath: (f: BuiltItem['builtFiles'][number]) => string) => ({
  $schema: REGISTRY_SCHEMA,
  name: 'kinetik',
  homepage: REGISTRY_URL,
  items: items.map((item) => ({
    name: item.name,
    type: registryType(item),
    title: item.title,
    description: item.description,
    ...(item.meta ? { categories: [item.meta.category] } : null),
    dependencies: installDependencies(item.dependencies),
    registryDependencies: item.registryDependencies.map(itemUrl),
    files: item.builtFiles.map((f) => ({
      path: filePath(f),
      type: 'registry:file',
      target: f.target,
    })),
    meta: itemMeta(item),
  })),
});

emit('public/r/registry.json', json(index((f) => publicPath(f.target))));
emit('registry.json', json(index((f) => installPath(f.target))));

// Demo index consumed by the playground and the docs site.
const components = items.filter((i) => i.kind !== 'shared');
const ident = (name: string) => name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
const demoLines = [
  '// Generated by scripts/build-registry.ts. Do not edit.',
  "import type { ComponentType } from 'react';",
  '',
  "import type { Controls } from './demo-kit/types';",
  ...components.map(
    (c) =>
      `import * as ${ident(c.name)} from './${path.relative(REGISTRY_DIR, c.dir!).split(path.sep).join('/')}/demo';`,
  ),
  '',
  `export const categories = ${JSON.stringify(CATEGORIES, null, 2)} as const;`,
  '',
  'export type DemoEntry = {',
  '  name: string;',
  '  title: string;',
  '  description: string;',
  '  category: keyof typeof categories;',
  '  phase: 1 | 2 | 3;',
  "  web: 'live' | 'device-only';",
  '  version: string;',
  '  controls: Controls;',
  '  // eslint-disable-next-line @typescript-eslint/no-explicit-any',
  '  Demo: ComponentType<any>;',
  '};',
  '',
  'export const demos: DemoEntry[] = [',
  ...components.map((c) => {
    const m = c.meta!;
    return `  { name: ${JSON.stringify(c.name)}, title: ${JSON.stringify(c.title)}, description: ${JSON.stringify(
      c.description,
    )}, category: ${JSON.stringify(m.category)}, phase: ${m.phase}, web: ${JSON.stringify(m.web)}, version: ${JSON.stringify(
      c.version,
    )}, controls: ${ident(c.name)}.controls, Demo: ${ident(c.name)}.default },`;
  }),
  '];',
  '',
];
emit(path.relative(ROOT, path.join(REGISTRY_DIR, 'demos.generated.ts')), demoLines.join('\n'));

// Write or verify.
const stale: string[] = [];
for (const [file, content] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    stale.push(path.relative(ROOT, file));
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}

// Remove outputs that no longer correspond to an item.
const expected = new Set(outputs.keys());
const walk = (dir: string): string[] =>
  fs.existsSync(dir)
    ? fs
        .readdirSync(dir, { withFileTypes: true })
        .flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]))
    : [];
for (const file of walk(PUBLIC_DIR)) {
  if (expected.has(file)) continue;
  if (check) stale.push(`${path.relative(ROOT, file)} (orphaned)`);
  else fs.rmSync(file);
}

if (check && stale.length) {
  console.error(`Registry output is stale. Run \`pnpm build:registry\`.\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(
  `${check ? 'Checked' : 'Built'} ${items.length} registry items (${items.filter((i) => i.kind === 'component').length} components, ${items.filter((i) => i.kind === 'template').length} templates).`,
);
