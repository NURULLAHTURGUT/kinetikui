/**
 * Writes docs/accessibility.md: the accessibility checklist for every
 * component and screen template, from item.json plus the latest audits.
 *
 *   pnpm tsx scripts/a11y/report.ts
 *
 * Reads tmp/a11y-device.json from scripts/a11y/device-audit.py when present
 * (the Android accessibility-tree audit); without it the device column keeps
 * the results already in the document.
 */
import fs from 'node:fs';
import path from 'node:path';

import prettier from 'prettier';

import { ROOT, loadItems } from '../lib/registry';

type DeviceResult = { interactive: number | null; issues: string[] };

const OUT = path.join(ROOT, 'docs', 'accessibility.md');
const deviceFile = path.join(ROOT, 'tmp', 'a11y-device.json');
const device: Record<string, DeviceResult> = fs.existsSync(deviceFile)
  ? JSON.parse(fs.readFileSync(deviceFile, 'utf8'))
  : {};

// Keep earlier device results for rows the latest run did not cover.
const previous = new Map<string, string>();
if (fs.existsSync(OUT)) {
  for (const line of fs.readFileSync(OUT, 'utf8').split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    if (cells.length > 7 && cells[1]?.startsWith('[')) previous.set(cells[1], cells[6] ?? '');
  }
}

const items = loadItems().filter((i) => i.kind !== 'shared' && i.meta);
// Backslashes first, so the escapes added for pipes are not themselves escaped.
const cell = (s: string) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

const rows = items.map((item) => {
  const m = item.meta!;
  const link = `[${item.title}](../packages/registry/${item.kind === 'template' ? 'templates' : 'items'}/${item.name}/docs.mdx)`;
  const d = device[item.name];
  const deviceCell = d
    ? d.issues.length === 0
      ? `✅ ${d.interactive} controls`
      : `⚠️ ${d.issues.map(cell).join('; ')}`
    : (previous.get(link) ?? '—');
  return `| ${link} | ${cell(m.a11y.reducedMotion)} | ${cell(m.a11y.screenReader)} | ${cell(m.a11y.touchTarget)} | ✅ | ${deviceCell} | Pending |`;
});

const doc = `# Accessibility checklist

Generated by \`scripts/a11y/report.ts\`. Do not edit by hand.

Every component and screen template is checked three ways:

1. **Automated (Jest)** — \`packages/registry/a11y/a11y.test.tsx\` renders every demo and fails on a pressable without a role, an interactive element without an accessible name, an explicitly sized target under 44 pt (unless \`hitSlop\` covers it), custom actions without a handler, or an adjustable element without increment and decrement. Every demo is also rendered with reduced motion forced on.
2. **Device tree (Android)** — \`scripts/a11y/device-audit.py\` opens each demo in the playground and reads the accessibility tree TalkBack sees (\`uiautomator\`): unlabelled controls and targets under 44 dp are flagged.
3. **Screen reader by hand (TalkBack, VoiceOver)** — needs a person and a real device; pending.

Reduced motion, screen reader and touch target notes come from each item's \`item.json\` and are shown on its docs page.

| Item | Reduced motion | Screen reader | Touch target | Jest audit | Android tree | TalkBack / VoiceOver |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;

// Formatted like every other file, so regenerating never breaks the format check.
async function write() {
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, await prettier.format(doc, { ...options, filepath: OUT }));
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${rows.length} items).`);
}

write().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
